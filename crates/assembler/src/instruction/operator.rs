use core::str::FromStr;

use seaside_constants::{
    NumberFormat, Opcode,
    fn_codes::{
        Coprocessor0Fn, Coprocessor1Fn, Coprocessor1RegisterImmediateFn, RegisterImmediateFn,
        Special2Fn, SpecialFn,
    },
};

use super::macros::*;

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum Operator {
    Special {
        r#fn: SpecialFn,
        condition: bool,
    },
    RegisterImmediate(RegisterImmediateFn),
    Jump,
    JumpAndLink,
    BranchEqual,
    BranchNotEqual,
    BranchLessEqualZero,
    BranchGreaterThanZero,
    AddImmediate,
    AddImmediateUnsigned,
    SetLessThanImmediate,
    SetLessThanImmediateUnsigned,
    AndImmediate,
    OrImmediate,
    XorImmediate,
    LoadUpperImmediate,
    Coprocessor0(Coprocessor0Fn),
    Coprocessor1 {
        r#fn: Coprocessor1Fn,
        fmt: NumberFormat,
        condition: bool,
    },
    Coprocessor1RegisterImmediate {
        r#fn: Coprocessor1RegisterImmediateFn,
        condition: bool,
    },
    Special2(Special2Fn),
    LoadByte,
    LoadHalf,
    LoadWordLeft,
    LoadWord,
    LoadByteUnsigned,
    LoadHalfUnsigned,
    LoadWordRight,
    StoreByte,
    StoreHalf,
    StoreWordLeft,
    StoreWord,
    StoreConditional,
    StoreWordRight,
    LoadLinked,
    LoadWordCoprocessor1,
    LoadDoubleCoprocessor1,
    StoreWordCoprocessor1,
    StoreDoubleCoprocessor1,
}

impl Operator {
    pub fn op_or_fn_code(&self) -> u8 {
        use Operator::*;
        match self {
            Special { r#fn, .. } => *r#fn as _,
            RegisterImmediate(r#fn) => *r#fn as _,
            Jump => Opcode::Jump as _,
            JumpAndLink => Opcode::JumpAndLink as _,
            BranchEqual => Opcode::BranchEqual as _,
            BranchNotEqual => Opcode::BranchNotEqual as _,
            BranchLessEqualZero => Opcode::BranchLessEqualZero as _,
            BranchGreaterThanZero => Opcode::BranchGreaterThanZero as _,
            AddImmediate => Opcode::AddImmediate as _,
            AddImmediateUnsigned => Opcode::AddImmediateUnsigned as _,
            SetLessThanImmediate => Opcode::SetLessThanImmediate as _,
            SetLessThanImmediateUnsigned => Opcode::SetLessThanImmediateUnsigned as _,
            AndImmediate => Opcode::AndImmediate as _,
            OrImmediate => Opcode::OrImmediate as _,
            XorImmediate => Opcode::XorImmediate as _,
            LoadUpperImmediate => Opcode::LoadUpperImmediate as _,
            Coprocessor0(r#fn) => *r#fn as _,
            Coprocessor1 { r#fn, .. } => *r#fn as _,
            Coprocessor1RegisterImmediate { r#fn, .. } => *r#fn as _,
            Special2(r#fn) => *r#fn as _,
            LoadByte => Opcode::LoadByte as _,
            LoadHalf => Opcode::LoadHalf as _,
            LoadWordLeft => Opcode::LoadWordLeft as _,
            LoadWord => Opcode::LoadWord as _,
            LoadByteUnsigned => Opcode::LoadByteUnsigned as _,
            LoadHalfUnsigned => Opcode::LoadHalfUnsigned as _,
            LoadWordRight => Opcode::LoadWordRight as _,
            StoreByte => Opcode::StoreByte as _,
            StoreHalf => Opcode::StoreHalf as _,
            StoreWordLeft => Opcode::StoreWordLeft as _,
            StoreWord => Opcode::StoreWord as _,
            StoreConditional => Opcode::StoreConditional as _,
            StoreWordRight => Opcode::StoreWordRight as _,
            LoadLinked => Opcode::LoadLinked as _,
            LoadWordCoprocessor1 => Opcode::LoadWordCoprocessor1 as _,
            LoadDoubleCoprocessor1 => Opcode::LoadDoubleCoprocessor1 as _,
            StoreWordCoprocessor1 => Opcode::StoreWordCoprocessor1 as _,
            StoreDoubleCoprocessor1 => Opcode::StoreDoubleCoprocessor1 as _,
        }
    }

    pub const fn new_special(r#fn: SpecialFn, condition: bool) -> Self {
        Self::Special { r#fn, condition }
    }

    pub const fn new_coprocessor_1(
        r#fn: Coprocessor1Fn,
        fmt: NumberFormat,
        condition: bool,
    ) -> Self {
        Self::Coprocessor1 {
            r#fn,
            fmt,
            condition,
        }
    }
}

