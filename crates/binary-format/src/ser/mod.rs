use std::io;

use serde::Serialize;

use crate::Error;

pub fn to_writer<W, T>(writer: W, value: &T) -> Result<(), Error>
where
    W: io::Write,
    T: ?Sized + Serialize,
{
    let mut serializer = Serializer { output: writer };
    value.serialize(&mut serializer)
}

pub fn to_bytes<T>(value: &T) -> Result<(), Error>
where
    T: ?Sized + Serialize,
{
    to_writer(Vec::new(), value)
}

